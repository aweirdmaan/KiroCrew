"""The read/write surface the board app requires of a tracker client - mirrors
``apps/builtins/issue_radar/backend/provider.py``'s ``ProviderClient`` Protocol
and its module-as-client dispatch pattern.
"""

from __future__ import annotations

from typing import Protocol

from kiro_crew.board.tracker.types import ProjectConfig, StorySummary


class BoardTrackerClient(Protocol):
    async def has_story(self, config: ProjectConfig, story_id: str) -> bool: ...
    async def list_stories(self, config: ProjectConfig) -> list[StorySummary]: ...
    async def get_story_detail(self, config: ProjectConfig, story_id: str) -> dict | None: ...
    async def add_comment(self, config: ProjectConfig, story_id: str, text: str) -> bool: ...
    async def update_story(
        self, config: ProjectConfig, story_id: str, *,
        title: str | None = None, description: str | None = None,
        start_date: str | None = None, due_date: str | None = None,
        rank: float | None = None, priority: int | None = None,
        story_points: float | None = None,
    ) -> bool: ...
    async def add_dependency(self, config: ProjectConfig, story_id: str, depends_on_id: str) -> bool: ...
    async def remove_dependency(self, config: ProjectConfig, story_id: str, depends_on_id: str) -> bool: ...
    async def get_phase(self, config: ProjectConfig, story_id: str) -> str | None: ...
    async def set_phase(self, config: ProjectConfig, story_id: str, new_phase: str) -> bool: ...
    async def last_gate_comment(self, config: ProjectConfig, story_id: str) -> str | None: ...
    async def last_recommendation_comment(self, config: ProjectConfig, story_id: str) -> str | None: ...
